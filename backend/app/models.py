"""
Pydantic models for DataSentinel AI.

These define the shape of data flowing through the API.
Every finding has a stable structure with ID, category, severity,
evidence, and recommended actions — no fabricated metrics.
"""

from pydantic import BaseModel, Field
from typing import Optional
from enum import Enum
from datetime import datetime


class Severity(str, Enum):
    """Issue severity levels with clear definitions."""
    CRITICAL = "critical"   # Data is unusable without fixing this
    HIGH = "high"           # Significant reliability risk
    MEDIUM = "medium"       # Notable issue worth investigating
    LOW = "low"             # Minor observation, may be acceptable
    INFO = "info"           # Informational finding, no action needed


class IssueCategory(str, Enum):
    """Categories of data quality issues."""
    COMPLETENESS = "completeness"
    UNIQUENESS = "uniqueness"
    VALIDITY = "validity"
    CONSISTENCY = "consistency"


class DataQualityFinding(BaseModel):
    """
    A single data quality finding with full evidence.

    Every finding is deterministic — generated by Python validation
    functions, not invented by an LLM.
    """
    issue_id: str = Field(description="Stable identifier like 'completeness-col_name-001'")
    category: IssueCategory
    severity: Severity
    title: str = Field(description="Short human-readable title")
    description: str = Field(description="Detailed explanation of the issue")
    column: Optional[str] = Field(default=None, description="Affected column name, if applicable")
    count: Optional[int] = Field(default=None, description="Exact count of affected rows/values")
    total: Optional[int] = Field(default=None, description="Total rows/values checked")
    percentage: Optional[float] = Field(default=None, description="Percentage affected")
    evidence: str = Field(description="How this was detected — calculation method and data")
    recommendation: str = Field(description="What the user should investigate or do next")


class ColumnProfile(BaseModel):
    """Profile of a single column in the dataset."""
    name: str
    dtype: str
    non_null_count: int
    null_count: int
    missing_count: int = Field(description="Null, empty-string, or whitespace-only cells")
    null_percentage: float
    unique_count: int
    sample_values: list


class DatasetProfile(BaseModel):
    """Summary profile of an uploaded dataset."""
    filename: str
    row_count: int
    column_count: int
    columns: list[ColumnProfile]
    memory_usage_mb: float
    upload_timestamp: str


class QualityScore(BaseModel):
    """
    Transparent quality score with documented formula.

    Score = weighted average of category scores.
    Each category score = 100 * (1 - issue_rate_for_category).
    Weights are documented in config.py and shown in the UI.
    """
    overall_score: float = Field(description="0-100 score, higher is better")
    completeness_score: float
    uniqueness_score: float
    validity_score: float
    consistency_score: float
    formula_explanation: str
    weights: dict


class AnalysisResult(BaseModel):
    """Complete analysis result returned to the frontend."""
    dataset_id: str
    profile: DatasetProfile
    quality_score: QualityScore
    findings: list[DataQualityFinding]
    analysis_timestamp: str
    total_issues: int
    issues_by_severity: dict
    issues_by_category: dict
    csv_warnings: list[str] = Field(default_factory=list, description="CSV parsing normalizations applied before analysis")


class InvestigationRequest(BaseModel):
    """Request to investigate a specific finding."""
    dataset_id: str
    issue_id: Optional[str] = None
    question: str


class InvestigationResponse(BaseModel):
    """Response from the AI investigation workflow."""
    answer: str
    evidence_used: list[str]
    tools_called: list[str]
    mode: str = Field(description="'ai' or 'rule-based' depending on API key availability")
    suggested_code: Optional[str] = None
    code_explanation: Optional[str] = None
    disclaimer: str = "Review all suggestions before acting on them. This analysis is based on automated checks and may not capture all context."
